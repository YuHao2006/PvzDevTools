#include "NativeBuild.h"
#include <algorithm>
#include <cmath>
#include <cstring>
#include <regex>

namespace pvz::build
{
void PackAtlas(const fs::path &manifest, const fs::path &compiler, const fs::path &output,
               const fs::path &cache)
{
    const auto document = ReadJson(manifest);
    Require(document.at("format") == "pvz-sprite-atlas-v1", "Unsupported sprite atlas manifest");
    const auto name = document.at("name").get<std::string>();
    Require(std::regex_match(name, std::regex("[A-Z][A-Za-z0-9_]*")), "Invalid atlas name");
    const auto &sprites = document.at("sprites");
    Require(sprites.is_array() && !sprites.empty(), "Atlas needs at least one sprite");
    std::set<std::string> names;
    std::vector<Image> images;
    std::vector<std::array<unsigned, 2>> logicalSizes;
    Json sizes = Json::array(), rows = Json::array();
    for (const auto &sprite : sprites)
    {
        const auto symbol = sprite.at("name").get<std::string>();
        Require(std::regex_match(symbol, std::regex("[A-Z][A-Z0-9_]*")) && names.insert(symbol).second,
                "Sprite names must be unique uppercase C++ identifiers");
        auto path = fs::canonical(manifest.parent_path() / sprite.at("image").get<std::string>());
        const std::string key = "source.png";
        ImageDescriptor recipe;
        recipe.path = key;
        auto image = DecodeImage(recipe, Files{{key, path}});
        const auto sourceWidth = image.width, sourceHeight = image.height;
        const auto rect = sprite.value("rect", Json{0, 0, image.width, image.height});
        Require(rect.is_array() && rect.size() == 4, "Invalid sprite rectangle");
        for (const auto &value : rect)
            Require(value.is_number_integer() && value.get<long long>() >= 0 &&
                        value.get<unsigned long long>() <= 0xffffffffULL,
                    "Invalid sprite rectangle coordinate");
        unsigned x = rect[0], y = rect[1], width = rect[2], height = rect[3];
        Require(width && height && x <= image.width && y <= image.height &&
                    width <= image.width - x && height <= image.height - y,
                "Sprite rectangle outside source image");
        Require(width <= 4092 && height <= 4092, "Sprite plus padding exceeds 4096");
        if (x || y || width != image.width || height != image.height)
        {
            Bytes pixels(std::size_t(width) * height * 4);
            for (unsigned row = 0; row < height; ++row)
                std::memcpy(pixels.data() + std::size_t(row) * width * 4,
                            image.rgba.data() + (std::size_t(y + row) * image.width + x) * 4, width * 4);
            image.width = width; image.height = height; image.rgba = std::move(pixels);
        }
        const auto logical = sprite.value("logical_size", Json{width, height});
        Require(logical.is_array() && logical.size() == 2, "Invalid logical size");
        for (const auto &value : logical)
            Require(value.is_number_integer() && value.get<long long>() > 0 &&
                        value.get<unsigned long long>() <= 0xffffffffULL,
                    "Logical dimensions must be positive unsigned integers");
        logicalSizes.push_back({logical[0].get<unsigned>(), logical[1].get<unsigned>()});
        sizes.push_back({image.width, image.height});
        rows.push_back({{"name", symbol}, {"image", sprite.at("image")}, {"source_rect", rect},
                        {"source_size", {sourceWidth, sourceHeight}}, {"logical_size", logical},
                        {"rgba_sha256", Sha256(image.rgba)}});
        images.push_back(std::move(image));
    }
    AtlasSettings settings;
    settings.seconds = document.value("time_limit_seconds", 60.0);
    settings.requireOptimal = document.value("require_optimal", false);
    Require(std::isfinite(settings.seconds) && settings.seconds >= 0, "Invalid atlas time budget");
    const auto work = cache / name;
    fs::create_directories(work);
    const auto initial = NativeLayouts(compiler, {sizes}, work);
    const auto layout = ExactLayout(sizes, initial[0], settings, cache / "atlas-layout-cache", work / "seed");
    std::vector<const Image *> pointers;
    for (const auto &image : images) pointers.push_back(&image);
    const auto packed = EncodePng(PackImages(pointers, layout));
    const auto width = layout.at("width").get<unsigned>(), height = layout.at("height").get<unsigned>();
    std::string header = "// Generated by pack-atlas. Pixel sizes and UVs are separate.\n#pragma once\nnamespace " + name + " {\n";
    header += "enum class Sprite : unsigned int {\n";
    for (const auto &row : rows) header += "    " + row["name"].get<std::string>() + ",\n";
    header += "    Count\n};\nstruct Region { float u0, v0, u1, v1; unsigned int width, height; };\n";
    header += "extern const Region Images[" + std::to_string(rows.size()) + "];\n}\n";
    std::string cpp = "#include \"" + name + ".h\"\nnamespace " + name + " {\nconst Region Images[" + std::to_string(rows.size()) + "] = {\n";
    for (std::size_t i = 0; i < rows.size(); ++i)
    {
        const auto &r = layout["regions"][i];
        const unsigned x = r[0], y = r[1], w = r[2], h = r[3];
        rows[i]["region"] = r;
        rows[i]["uv"] = {double(x) / width, double(y) / height, double(x + w) / width, double(y + h) / height};
        cpp += "    {" + CppFloat(double(x) / width) + ", " + CppFloat(double(y) / height) + ", " +
               CppFloat(double(x + w) / width) + ", " + CppFloat(double(y + h) / height) + ", " +
               std::to_string(logicalSizes[i][0]) + ", " + std::to_string(logicalSizes[i][1]) + "},\n";
    }
    cpp += "};\n}\n";
    // Validate/decode/solve/encode everything before publishing any result.
    Publish(output / (name + ".png"), packed);
    Publish(output / (name + ".h"), header);
    Publish(output / (name + ".cpp"), cpp);
    Publish(output / (name + ".json"), Json{{"format", "pvz-sprite-atlas-v1"}, {"name", name},
            {"width", width}, {"height", height}, {"padding", 2}, {"sprites", rows}, {"packing", layout}}.dump(2) + "\n");
}
} // namespace pvz::build
